import type { Metadata } from "next";
import { cookies } from "next/headers";
import { Geist, Geist_Mono } from "next/font/google";
import { AntdRegistry } from "@ant-design/nextjs-registry";
import AntdConfigProvider from "@/components/AntdConfigProvider";
import type { ThemeMode } from "@/components/useThemeMode";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// 主题 cookie（由 components/useThemeMode.ts 在客户端每次主题变化时镜像写入）：
// 服务端读取后决定 SSR 渲染的 antd token，首屏即用户当前主题，消除刷新闪变
export default async function RootLayout({ children }: LayoutProps<"/">) {
  const jar = await cookies();
  const rawMode = jar.get("cb_theme")?.value;
  const initialTheme = {
    mode: (rawMode === "light" || rawMode === "dark" || rawMode === "system"
      ? rawMode
      : ("system" as const)) as ThemeMode,
    dark: jar.get("cb_theme_dark")?.value === "1",
  };

  return (
    <html
      lang="zh-CN"
      // 内联脚本会在 hydration 前给 html 注入主题类（dark/cb-light），与 SSR 的
      // className 必然不一致，属预期行为，抑制该元素自身的属性比较（不影响子树）
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {/* 首屏 HTML 解析阶段（渲染任何内容前）同步设置 html 主题类：
            覆盖 CSS 变量层（body 背景 / globals.css），与 SSR antd token 配合 */}
        <script
          dangerouslySetInnerHTML={{
            __html:
              "(function(){try{var m=document.cookie.match(/(?:^|; )cb_theme_dark=(\\d)/);" +
              "if(m){m[1]==='1'?document.documentElement.classList.add('dark')" +
              ":document.documentElement.classList.add('cb-light');}}catch(e){}})()",
          }}
        />
        <AntdRegistry>
          <AntdConfigProvider initialTheme={initialTheme}>
            {children}
          </AntdConfigProvider>
        </AntdRegistry>
      </body>
    </html>
  );
}
